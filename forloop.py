#for loop - iterating through a sequence

#looping through a list
fruits=["Oranges","Apples","Bananas","Mangoes"]
for fruits in fruits:
    print(fruits)
#looping through a string
for x in "Hello":
    print(x)
#looping through a range
for z in range(2,6):
    print(z)
for b in range(9):
    print(b)

#step
for c in range(10,3,2):
    print(c)
